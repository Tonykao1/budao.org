const test = require('node:test');
const assert = require('node:assert/strict');

const DNA = require('../pasture-sheep-dna.js');

const DIMENSIONS = ['woolColor','faceColor','woolShape','bodyShape','ears','expression','marking','forelock'];

test('default V2 DNA has exactly the approved eight dimensions', () => {
  const dna = DNA.defaultV2();
  assert.equal(dna.version, 2);
  assert.deepEqual(Object.keys(dna).sort(), ['version', ...DIMENSIONS].sort());
  for (const key of DIMENSIONS) assert.ok(DNA.enums[key].includes(dna[key]), `${key} default must be approved`);
  assert.deepEqual(Object.fromEntries(Object.entries(DNA.enums).map(([k,v]) => [k,v.length])), {
    woolColor:10, faceColor:8, woolShape:4, bodyShape:4, ears:4, expression:4, marking:7, forelock:5
  });
});

test('validation rejects unknown values and normalization repairs missing keys only', () => {
  const valid = DNA.defaultV2();
  assert.equal(DNA.validateV2(valid), true);
  assert.equal(DNA.validateV2({...valid, version:3}), false);
  assert.equal(DNA.validateV2({...valid, ears:'horns'}), false);
  assert.equal(DNA.validateV2({...valid, ninth:'nope'}), false);

  const normalized = DNA.normalizeV2({version:2, woolColor:'black'});
  assert.equal(normalized.version, 2);
  assert.equal(normalized.woolColor, 'black');
  assert.deepEqual(Object.keys(normalized).sort(), ['version', ...DIMENSIONS].sort());
  assert.equal(DNA.validateV2(normalized), true);
});

test('random V2 always validates and avoids unreadable dark-on-dark faces', () => {
  const darkWool = new Set(['charcoal','black']);
  const darkFace = new Set(['slate','deepBrown','charcoal']);
  for (let i=0;i<128;i++) {
    let n = i;
    const random = () => ((n = (n * 1103515245 + 12345) >>> 0) % 10000) / 10000;
    const dna = DNA.randomV2(random);
    assert.equal(DNA.validateV2(dna), true);
    if (darkWool.has(dna.woolColor)) assert.equal(darkFace.has(dna.faceColor), false);
  }
});

test('legacy fallback is generated by V2 DNA, not accepted from client', () => {
  const legacy = DNA.toLegacy({...DNA.defaultV2(), woolColor:'black', faceColor:'ivory', marking:'forehead'});
  assert.match(legacy.bodyColor, /^#[0-9a-f]{6}$/i);
  assert.match(legacy.headColor, /^#[0-9a-f]{6}$/i);
  assert.ok(['NONE','FACE','BACK','SOCKS'].includes(legacy.marking));
});
